#!/usr/bin/env bash
# ReconKit — scoped recon for authorized engagements only.
# Usage: ./recon.sh <target-domain>   (target must be a line in $SCOPE_FILE)
set -euo pipefail

TARGET="${1:-}"
SCOPE_FILE="${SCOPE_FILE:-scope.txt}"
OUT_DIR="${OUT_DIR:-engagements}"
NMAP_ARGS="${NMAP_ARGS:--T3 -p- --open}"

usage() {
  echo "usage: $0 <target-domain>" >&2
  echo "  target must appear verbatim in $SCOPE_FILE (one per line)" >&2
  exit 64
}

[[ -n "$TARGET" ]] || usage
[[ -f "$SCOPE_FILE" ]] || { echo "no scope file: $SCOPE_FILE" >&2; exit 66; }

# ---- authorization gate -------------------------------------------------
if ! grep -qixF "$TARGET" "$SCOPE_FILE"; then
  echo "refusing: $TARGET is not in the signed scope list ($SCOPE_FILE)" >&2
  exit 2
fi

OUT="$OUT_DIR/$(date +%F)/$TARGET"
LOG="$OUT/commands.log"
mkdir -p "$OUT"

log() { echo "[$(date -u +%H:%M:%SZ)] $*" | tee -a "$LOG"; }
run() { log "$*"; "$@" 2>>"$LOG"; }

log "engaging $TARGET — scope file: $SCOPE_FILE"

# ---- 1. subdomains ------------------------------------------------------
log "[1/4] passive subdomain enumeration"
if command -v subfinder >/dev/null; then
  run subfinder -d "$TARGET" -silent > "$OUT/subdomains.txt" || true
else
  echo "$TARGET" > "$OUT/subdomains.txt"
  log "subfinder not found — continuing with the apex domain only"
fi

# ---- 2. ports -----------------------------------------------------------
log "[2/4] port discovery ($NMAP_ARGS)"
if command -v nmap >/dev/null; then
  # shellcheck disable=SC2086
  run nmap -iL "$OUT/subdomains.txt" $NMAP_ARGS -oA "$OUT/ports" > "$OUT/ports.txt" || true
else
  log "nmap not found — skipping port discovery"
fi

# ---- 3. tls -------------------------------------------------------------
log "[3/4] tls fingerprints"
: > "$OUT/tls.md"
while IFS= read -r host; do
  [[ -z "$host" ]] && continue
  echo "## $host" >> "$OUT/tls.md"
  timeout 10 openssl s_client -connect "$host:443" -servername "$host" </dev/null 2>/dev/null \
    | openssl x509 -noout -subject -issuer -dates >> "$OUT/tls.md" 2>/dev/null || echo "_no tls on 443_" >> "$OUT/tls.md"
  echo >> "$OUT/tls.md"
done < "$OUT/subdomains.txt"

# ---- 4. report ----------------------------------------------------------
log "[4/4] writing report"
cat > "$OUT/report.md" <<EOF
# Recon report — $TARGET

- engagement date: $(date +%F)
- generated by: reconkit
- scope file: \`$SCOPE_FILE\`

## Subdomains

\`\`\`
$(wc -l < "$OUT/subdomains.txt" | tr -d ' ') hosts
\`\`\`

## Ports

\`\`\`
$(grep -E '^[0-9]+/tcp' "$OUT/ports.txt" 2>/dev/null | head -50 || echo "see ports.txt")
\`\`\`

## TLS

$(cat "$OUT/tls.md")

## Command log

See \`commands.log\` — every command in this engagement is timestamped and recorded.
EOF

log "done -> $OUT (attach report.md to the deliverable)"
